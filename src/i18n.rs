use std::sync::{OnceLock, RwLock};

static LOCALE: OnceLock<RwLock<String>> = OnceLock::new();

/// Every selectable language in menu order. `auto` resolves through the system
/// locale; the rest are matched literally by the `(locale, key)` lookups.
pub const LANGUAGES: [&str; 15] = [
    "auto", "zh-Hans", "zh-Hant", "en", "ja", "ko", "id", "ms", "vi", "es", "fr", "it", "de", "ru",
    "tr",
];

pub fn set_locale(value: &str) {
    let value = if value == "auto" {
        system_locale()
    } else {
        value.to_owned()
    };
    *LOCALE
        .get_or_init(|| RwLock::new("zh-Hans".into()))
        .write()
        .expect("locale lock") = value;
}

pub fn refresh_system_locale() -> bool {
    let value = system_locale();
    let mut locale = LOCALE
        .get_or_init(|| RwLock::new("zh-Hans".into()))
        .write()
        .expect("locale lock");
    if *locale == value {
        false
    } else {
        *locale = value;
        true
    }
}

fn locale() -> String {
    LOCALE
        .get_or_init(|| RwLock::new("zh-Hans".into()))
        .read()
        .expect("locale lock")
        .clone()
}
fn system_locale() -> String {
    #[cfg(target_os = "macos")]
    if let Some(value) = std::process::Command::new("/usr/bin/defaults")
        .args(["read", "-g", "AppleLanguages"])
        .output()
        .ok()
        .filter(|output| output.status.success())
        .map(|output| String::from_utf8_lossy(&output.stdout).to_lowercase())
    {
        if let Some(locale) = match_locale(&value) {
            return locale.to_owned();
        }
    }
    let value = std::env::var("LC_ALL")
        .or_else(|_| std::env::var("LANG"))
        .unwrap_or_default()
        .to_lowercase();
    match_locale(&value).unwrap_or("en").to_owned()
}

/// Map a system language list (`("en-US", "zh-Hans")`, `ko_KR.UTF-8`, …) onto
/// a supported locale, keeping the order in which the tags appear so the
/// user's preferred language wins. Unsupported tags yield `None` so the caller
/// can try the next source.
fn match_locale(value: &str) -> Option<&'static str> {
    value
        .split(|character: char| {
            !(character.is_ascii_alphanumeric() || character == '-' || character == '_')
        })
        .filter(|tag| !tag.is_empty())
        .find_map(locale_for_tag)
}

/// Resolve one language tag (`zh-Hant-TW`, `id-ID`, `en-US`, …) onto a
/// supported locale, or `None` when it is not one we ship.
fn locale_for_tag(tag: &str) -> Option<&'static str> {
    let lower = tag.to_ascii_lowercase();
    let mut parts = lower.split(['-', '_']);
    match parts.next()? {
        "zh" => {
            let traditional = parts.any(|part| matches!(part, "hant" | "tw" | "hk" | "mo"));
            Some(if traditional { "zh-Hant" } else { "zh-Hans" })
        }
        "ja" => Some("ja"),
        "ko" => Some("ko"),
        // `in` is the deprecated ISO code for Indonesian; macOS still uses it.
        "id" | "in" => Some("id"),
        "ms" => Some("ms"),
        "vi" => Some("vi"),
        "es" => Some("es"),
        "fr" => Some("fr"),
        "it" => Some("it"),
        "de" => Some("de"),
        "ru" => Some("ru"),
        "tr" => Some("tr"),
        "en" => Some("en"),
        _ => None,
    }
}

