    #[test]
    fn maps_language_tags_to_supported_locales() {
        assert_eq!(
            match_locale("(\n    \"ja-JP\",\n    \"en-US\"\n)"),
            Some("ja")
        );
        assert_eq!(match_locale("ko_KR.UTF-8"), Some("ko"));
        assert_eq!(match_locale("id_ID"), Some("id"));
        assert_eq!(match_locale("en-US"), Some("en"));
        assert_eq!(match_locale("zh-Hant-TW"), Some("zh-Hant"));
        assert_eq!(match_locale("zh_CN"), Some("zh-Hans"));
        // Codes only match whole tag components, never substrings.
        assert_eq!(match_locale("mid"), None);
        assert_eq!(match_locale("enigma"), None);
        assert_eq!(match_locale("nl-NL"), None);
        // The first supported language in the preference list wins.
        assert_eq!(match_locale("en-US, zh-Hans"), Some("en"));
        assert_eq!(
            match_locale("(\n    \"zh-Hant\",\n    \"en\"\n)"),
            Some("zh-Hant")
        );
    }

    #[test]
    fn every_language_translates_every_string() {
        for locale in LOCALES {
            for key in MENU_KEYS {
                assert!(!menu_for(locale, key).is_empty(), "{locale} menu {key}");
            }
            for key in TEXT_KEYS {
                assert!(!text_for(locale, key).is_empty(), "{locale} text {key}");
            }
            for key in STATE_KEYS {
                assert!(!state_for(locale, key).is_empty(), "{locale} state {key}");
            }
        }
    }

    /// A missing arm silently falls back to Simplified Chinese, so a string
    /// that still equals the Chinese one means the key was never wired up for
    /// that language.
    #[test]
    fn translated_languages_do_not_fall_back_to_chinese() {
        for locale in TRANSLATED {
            for key in MENU_KEYS {
                if !SHARED_WITH_CHINESE.contains(&(locale, key)) {
                    assert_ne!(
                        menu_for(locale, key),
                        menu_for("zh-Hans", key),
                        "{locale} menu {key}"
                    );
                }
            }
            for key in TEXT_KEYS {
                assert_ne!(
                    text_for(locale, key),
                    text_for("zh-Hans", key),
                    "{locale} text {key}"
                );
            }
            for key in STATE_KEYS {
                assert_ne!(
                    state_for(locale, key),
                    state_for("zh-Hans", key),
                    "{locale} state {key}"
                );
            }
        }
    }
